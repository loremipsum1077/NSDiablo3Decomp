bdRemoteTaskRef bdMessaging::sendGlobalInstantMessage(const bdOnlineUserID recipientUID,
                                                      const void *const message,
                                                      const bdUInt msgSize)
{
    bdRemoteTaskRef task;
    const bdUInt actualMsgSize = msgSize < 4096 ? msgSize : 4096;
    if (msgSize > 4096) {

        bdLogWarn("bdMessaging", "Message exceeds maximum size");
    }


    const bdUInt taskSize = actualMsgSize + 87;
    bdTaskByteBufferRef buffer = new bdTaskByteBuffer(taskSize, true);
    bdRemoteTaskManager::initTaskBuffer(buffer, 6, 14);
    bdBool wroteParam = true;
    wroteParam = wroteParam && buffer->writeUInt64(recipientUID);
    wroteParam = wroteParam && buffer->writeBlob(message, actualMsgSize);
    if (wroteParam) {

        const bdLobbyErrorCode startTaskResult = m_remoteTaskManager->startTask(task, buffer);
        if (startTaskResult != BD_NO_ERROR) {

            bdLogWarn("bdMessaging", "Failed to start task: %u", startTaskResult);
        }
    } else {


        bdLogWarn("bdMessaging", "Failed to serialize task parameters");
    }

    return task;
}













































































































































































































































































































