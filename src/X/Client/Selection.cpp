void SelectionInitializeForWorld()
{

    SelectionGlobals *& ptSelectionGlobals = CGameGet().ptSelectionGlobals;
    ptSelectionGlobals = (SelectionGlobals *)SigmaMemoryNew(sizeof(SelectionGlobals), 4, NULL, TRUE);

    ptSelectionGlobals->listSelectedRActors.Initialize(MemoryPoolsGetDATAIDListPool());
    ptSelectionGlobals->listRubberbandedRActors.Initialize(MemoryPoolsGetDATAIDListPool());
    ptSelectionGlobals->eState = SELSTATE_NONE;

    ptSelectionGlobals->eMouseButtonUsedToPick = -1;

    new (&ptSelectionGlobals->listRActorsHit) RActorIntersectArray;
    new (&ptSelectionGlobals->listRActorsHitFallback) RActorIntersectArray;
    ptSelectionGlobals->idNearestNecroCorpseRActor = RACTORID_INVALID;
    ptSelectionGlobals->flStereoDepth = 1.0f;
}






void SelectionDisposeForWorld()
{

    SelectionGlobals *& ptSelectionGlobals = CGameGet().ptSelectionGlobals;

    ptSelectionGlobals->listRActorsHit.~RActorIntersectArray();
    ptSelectionGlobals->listRActorsHitFallback.~RActorIntersectArray();

    ptSelectionGlobals->listSelectedRActors.Dispose();
    ptSelectionGlobals->listRubberbandedRActors.Dispose();
    SigmaMemoryFree(ptSelectionGlobals, NULL);
    ptSelectionGlobals = NULL;
}









































































































































































































































































































































































































































































































































































































































































































































































































