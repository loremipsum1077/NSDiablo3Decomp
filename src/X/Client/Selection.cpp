BOOL ScreenPickGroundWithOffset(const IVector2D & p, const Vector3D & wvOffset, Vector3D & wpIntersect, uint32 dwIntersectFlags, SSceneID idSScene, SSceneID * pidSSceneResult, SNO * psnoAppearance, int32 * pnSubobject, WorldDistance * pwdIntersect)
{









    LineSeg3D wline;


    ScreenPointToWorldLineSeg(p, wline, -1);


    wline.wr.wpOrigin += wvOffset;

    return IntersectGround(wline, wpIntersect, dwIntersectFlags, idSScene, pidSSceneResult, psnoAppearance, pnSubobject, pwdIntersect);
}












BOOL IntersectGround(const LineSeg3D & wline, Vector3D & wpIntersect, uint32 dwIntersectFlags, SSceneID idSScene, SSceneID * pidSSceneResult, SNO * psnoAppearance, int32 * pnSubobject, WorldDistance * pwdIntersect)
{








    BOOL bIntersect;

    SWorldID idSWorld = CGameGetCurrentSWorldID();

    StructureIntersectData tStructIntersect(idSWorld);
    tStructIntersect.wline = wline;
    tStructIntersect.dwIntersectFlags = dwIntersectFlags;

    if (idSScene != -1)
    {
        bIntersect = CSceneIntersectLineSeg(idSScene, tStructIntersect);
    }
    else
    {



        bIntersect = CScenesIntersectLineSeg(tStructIntersect, SkipHolodeckScenes);
    }




    if (bIntersect)
    {
        wpIntersect = tStructIntersect.wpIntersect;

        if (pidSSceneResult)
        {
            *pidSSceneResult = tStructIntersect.idSScene;
        }

        if (psnoAppearance)
        {
            *psnoAppearance = tStructIntersect.snoAppearance;
        }

        if (pnSubobject)
        {
            *pnSubobject = tStructIntersect.nSubobject;
        }

        if (pwdIntersect)
        {
            *pwdIntersect = tStructIntersect.wdIntersect;
        }
        return TRUE;
    }

    return FALSE;
}
