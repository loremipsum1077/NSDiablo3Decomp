void UISkills::BannerDropOnClick(const UIID & id) {
    RActorID idLocalPlayerRActor = LocalPlayerRActorGet();
    const RActor * ptPlayerRActor = RActorTryToGet(idLocalPlayerRActor);
    if (ptPlayerRActor != NULL && UI_TestID(id)) {
        SNO snoPower = GlobalSNOGet(GLOBALSNO_POWERS_BANNER_DROP);
        if (snoPower != SNO_NONE) {
            CPlayerInputClickWithPower(ptPlayerRActor, 39, snoPower, TRUE);
        }
    }
}















































void UISkills::GetSkillIconImages(SNO snoPower, const BOOL bInactive, ImageTextureFrame & tTexFrameNormal, ImageTextureFrame & tTexFrameMouseover, ImageTextureFrame & tTexFramePushed, ImageTextureFrame & tTexFrameRound) {
    ScopedPowerDefinitionLockR pdefPower(snoPower);
    if (bInactive) {
        ImageHandle hImageInactive = PowerGeneralTagGetInt(AutoPowerDefinitionR(pdefPower), 0x50728);
        ImageCollectionGetImageInfo(2, hImageInactive, tTexFrameNormal);
        tTexFrameMouseover = tTexFrameNormal;
        tTexFramePushed = tTexFrameNormal;
    } else {
        ImageHandle hImageNormal = PowerGeneralTagGetInt(AutoPowerDefinitionR(pdefPower), 0x50700);
        ImageHandle hImageMouseover = PowerGeneralTagGetInt(AutoPowerDefinitionR(pdefPower), 0x50710);
        ImageHandle hImagePushed = PowerGeneralTagGetInt(AutoPowerDefinitionR(pdefPower), 0x50720);
        ImageCollectionGetImageInfo(2, hImageNormal, tTexFrameNormal);
        ImageCollectionGetImageInfo(2, hImageMouseover, tTexFrameMouseover);
        ImageCollectionGetImageInfo(2, hImagePushed, tTexFramePushed);
    }
    ImageHandle hImageRound = PowerGeneralTagGetInt(AutoPowerDefinitionR(pdefPower), 0xaf000);
    if (hImageRound == 0) {
        tTexFrameRound = tTexFrameNormal;
    } else {
        ImageCollectionGetImageInfo(2, hImageRound, tTexFrameRound);
    }
}











































































































































































































































































































void UISkills::DisplayToggle(const UIID &) {
    BOOL fNewState = !UI_GetWindowFromID(UIDLG_SKILL_PAGE).IsActive();
    if (fNewState) {
        ActorCommonData * ptACD = ACDTryToGet(LocalPlayerACDGet());
        if (ptACD == NULL)
            return;
        if (!PlayerCanViewSkillorTrait(*ptACD)) {
            // 55 / 57 are GameError values with no recovered enumerator names.
            if (ACDIsParticipatingInTieredLootRun(*ptACD) || ACDIsParticipatingInSetDungeon(*ptACD)) {
                UIGame::DisplayError(GameErrorData(57), FALSE, NULL);
            } else {
                UIGame::DisplayError(GameErrorData(55), FALSE, NULL);
            }
            return;
        }
    }
    UISideScreenSetVisible(UIDLG_SKILL_PAGE, fNewState);
}
