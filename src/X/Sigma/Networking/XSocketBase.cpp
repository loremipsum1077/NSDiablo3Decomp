void XSocketBase::Close()
{

	if (reinterpret_cast<XSocketBaseInternal *>(m_tOpaque)->m_sock != -1)
	{
		if (closesocket(reinterpret_cast<XSocketBaseInternal *>(m_tOpaque)->m_sock) == -1)
		{
			WSAGetLastError();
		}
		reinterpret_cast<XSocketBaseInternal *>(m_tOpaque)->m_sock = -1;
	}
}





































































































































































































































































































// NON_MATCHING: 108 vs 104 bytes. Ours copies the sendto result to x8 and schedules
// mov w0,wzr before the store; tried if/return and if/else layouts on the DWARF lines.
XSocketBase::Result XSocketBase::SendTo(
	const void * pData,
	uint32 uBytes,
	const XNetAddress & tPeerAddress,
	uint32 & uBytesSent)
{
	int sendResult = sendto(
			reinterpret_cast<XSocketBaseInternal *>(m_tOpaque)->m_sock,
			pData,
		uBytes,
		0,
		reinterpret_cast<const sockaddr *>(&tPeerAddress),
		sizeof(sockaddr));


	if (sendResult != -1)
	{
		uBytesSent = sendResult;
		return RESULT_SUCCESS;
	}


	uBytesSent = 0;

	int32 nReturnVal = WSAGetLastError();
	if (nReturnVal == WSAEWOULDBLOCK)
	{
		return RESULT_WOULDBLOCK;
	}

	return RESULT_FAILURE;

}

































































